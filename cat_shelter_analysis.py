# 4. convert age to numeric

def convert_age_to_days(age):
    try:
        value = int(age.split()[0])
        if "year" in age:
            return value * 365
        elif "month" in age:
            return value * 30
        elif "week" in age:
            return value * 7
        else:
            return value
    except:
        return np.nan

cats["Age_days"] = cats["Age upon Outcome"].apply(convert_age_to_days)
cats = cats.dropna(subset=["Age_days"])

# create age groups

bins = [0, 180, 365, 1825, 10000]
labels = ["Kitten", "Young", "Adult", "Senior"]

cats["Age_group"] = pd.cut(cats["Age_days"], bins=bins, labels=labels)

# Distribution of shelter outcomes
